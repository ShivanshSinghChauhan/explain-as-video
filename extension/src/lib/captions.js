// Caption chunking, timeline estimation and caption/transcript exports.

import { countWords } from './text.js';

export const WORDS_PER_SECOND = 2.6; // typical TTS pace at rate 1.0

/** Split narration into caption-sized chunks on word boundaries. */
export function chunkCaption(text, maxChars = 70) {
  const words = String(text || '').split(/\s+/).filter(Boolean);
  const chunks = [];
  let cur = '';
  for (const w of words) {
    const next = cur ? `${cur} ${w}` : w;
    // Prefer to break after sentence punctuation once a chunk is reasonably full.
    if (next.length > maxChars && cur) {
      chunks.push(cur);
      cur = w;
    } else {
      cur = next;
      if (/[.!?]$/.test(w) && cur.length > maxChars * 0.5) {
        chunks.push(cur);
        cur = '';
      }
    }
  }
  if (cur) chunks.push(cur);
  return chunks;
}

export function estimateDurationMs(text, rate = 1) {
  const secs = countWords(text) / (WORDS_PER_SECOND * Math.max(0.25, rate));
  return Math.round(Math.max(1500, secs * 1000 + 400));
}

/**
 * Estimated timeline used for timer mode, WebM export and caption files.
 * Each scene: { start, end, cues: [{ start, end, text }] } in ms.
 */
export function buildTimeline(storyboard, rate = 1) {
  let t = 0;
  const scenes = storyboard.scenes.map((scene, index) => {
    const chunks = chunkCaption(scene.narration);
    const cues = [];
    let s = t + 300; // short visual lead-in before narration
    for (const text of chunks) {
      const d = estimateDurationMs(text, rate);
      cues.push({ start: s, end: s + d, text });
      s += d;
    }
    const start = t;
    const end = s + 700; // let the visual breathe after the last line
    t = end;
    return { index, start, end, cues };
  });
  return { duration: t, scenes };
}

function pad(n, w = 2) {
  return String(n).padStart(w, '0');
}

export function formatTimestamp(ms, sep = '.') {
  const total = Math.max(0, Math.round(ms));
  const h = Math.floor(total / 3600000);
  const m = Math.floor((total % 3600000) / 60000);
  const s = Math.floor((total % 60000) / 1000);
  return `${pad(h)}:${pad(m)}:${pad(s)}${sep}${pad(total % 1000, 3)}`;
}

// Cue text must not contain blank lines or "-->" (would break the cue format).
function cueText(t) {
  return t.replace(/-->/g, '→').replace(/\n+/g, ' ');
}

export function toWebVTT(timeline) {
  const lines = ['WEBVTT', ''];
  let n = 1;
  for (const sc of timeline.scenes) {
    for (const c of sc.cues) {
      lines.push(String(n++), `${formatTimestamp(c.start)} --> ${formatTimestamp(c.end)}`, cueText(c.text), '');
    }
  }
  return lines.join('\n');
}

export function toSRT(timeline) {
  const lines = [];
  let n = 1;
  for (const sc of timeline.scenes) {
    for (const c of sc.cues) {
      lines.push(String(n++), `${formatTimestamp(c.start, ',')} --> ${formatTimestamp(c.end, ',')}`, cueText(c.text), '');
    }
  }
  return lines.join('\n');
}

/** Slide outline as Markdown: headings, bullets and speaker notes. */
export function toMarkdownOutline(storyboard) {
  const md = (s) => String(s).replace(/([\\`*_[\]#<>|])/g, '\\$1');
  const out = [`# ${md(storyboard.title)}`, ''];
  storyboard.scenes.forEach((s, i) => {
    out.push(`## ${i + 1}. ${md(s.heading)}`, '');
    if (s.bullets.length) out.push(...s.bullets.map((b) => `- ${md(b)}`), '');
    out.push(`> Speaker notes: ${md(s.narration)}`, '');
  });
  return out.join('\n');
}

export function toTranscript(storyboard, meta = {}) {
  const out = [storyboard.title, '='.repeat(Math.min(60, storyboard.title.length)), ''];
  if (meta.sourceUrl) out.push(`Source: ${meta.sourceUrl}`);
  if (meta.generator) out.push(`Generated by: ${meta.generator}`);
  if (meta.sourceUrl || meta.generator) out.push('');
  storyboard.scenes.forEach((s, i) => {
    out.push(`${i + 1}. ${s.heading}`, s.narration);
    if (s.bullets.length) out.push(...s.bullets.map((b) => `   - ${b}`));
    out.push('');
  });
  return out.join('\n');
}
